#ifndef __CircularArc_h
#define __CircularArc_h

#include "Polyline.h"
#include "cg/include/geometry/Bounds3.h"
#include <cassert>

namespace cg
{ // begin namespace cg

template<IsReal R>
struct CircularArcLimits: public PolylineLimits
{
    // --- Line Segments ---
    static constexpr size_t MIN_NC = 2; // min n of segments
    static constexpr size_t MAX_NC = 40; // max n of segments

    // --- Arc Angle ---
    static constexpr R MIN_THETAC_EXCLUSIVE = 0; // min theta_c (exclusive)
    static constexpr R MAX_THETAC = 360; // max theta_c

}; // CircularArc Limits

template<IsReal R>
class CircularArc: public Polyline<R>
{
public:
  using type = CircularArc<R>;
  using value_type = R;
  using quat = Quaternion<R>;
  using vec3 = Vector3<R>;
  using mat3 = Matrix3x3<R>;
  using bounds = Bounds3<R>;
  using limits = CircularArcLimits<R>;

  /// @brief Contructor for a polyline generated by a circle arc with "TRS" factors
  CircularArc(float tc = 30, size_t nc = 4, R ep = 0, R tp = 0, R sp = 0, bool isOpen = false):
    _tc{tc},
    _nc{nc},
    _ep{ep},
    _tp{tp},
    _sp{sp},
    _isOpen{isOpen}
  {
    assert(_tc > limits::MIN_THETAC_EXCLUSIVE && _tc <= limits::MAX_THETAC 
      && _nc >= limits::MIN_NC && _nc <= limits::MAX_NC);
    _np = _tc < 360 ? _nc + 1 : _nc;
  }

  void set() override;

private:
  R _tc;
  size_t _nc;
  bool _isOpen;

}; // CircularArc

}

#endif // __CircularArc_h
