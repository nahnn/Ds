#ifndef __Polyline_h
#define __Polyline_h

#include "PolylineUtils.h"
#include "math/Matrix3x3.h"
#include <cassert>

namespace cg
{ // begin namespace cg
using index_t = unsigned;

/// @brief
// Polyline: Class that represents the discretization of a given curve.
template<IsReal R>
class Polyline
{
public:
  using type = Polyline<R>;
  using value_type = R;
  using quat = Quaternion<R>;
  using vec3 = Vector3<R>;
  using mat3 = Matrix3x3<R>;
  using limits = PolylineUtils::PolylineLimits;

  /// @brief Default constructor
  constexpr Polyline() = default;

  /// @brief Contructor for a polyline generated by a regular polygon with "TRS" factors
  Polyline(index_t np, float ep = 0, float tp = 0, float sp = 0): 
    _np{np}
  {
    assert(_np >= limits::MinNp && _np <= limits::MaxNp);
    set(ep, tp, sp);
  }

  /// @brief Contructor for a polyline generated by a circle arc with "TRS" factors
  Polyline(float tc, size_t nc, float ep = 0, float tp = 0, float sp = 0, bool isOpen = false)
  {
    assert(tc >= limits::MinTc && tc <= limits::MaxTc 
      && nc >= limits::MinNc && nc <= limits::MaxNc);
    _np = tc < 360 ? nc + 1 : nc;
    set(ep, tp, sp);
  }

  void set(const float& ep, const float& tp, const float& sp);

private:
  index_t _np{};
  vec3 _points[2 * limits::MaxNp];

}; // Polyline

} // end namespace cg

#endif // __Polyline_h
