/// @brief
// Polyline: Class that represents the discretization of a given curve.
template<IsReal R>
class Polyline
{
public:
  using type = Polyline<R>;
  using value_type = R;
  using quat = Quaternion<R>;
  using vec3 = Vector3<R>;
  using mat3 = Matrix3x3<R>;
  using bounds = Bounds3<R>;
  using limits = PolylineUtils::PolylineLimits<R>;

  /// @brief Default constructor
  constexpr Polyline() = default;

  /// @brief Contructor for a polyline generated by a regular polygon with "TRS" factors
  Polyline(index_t np, R ep = 0, R tp = 0, R sp = 0): 
    _np{np}
  {
    assert(_np >= limits::MinNp && _np <= limits::MaxNp);
    set(ep, tp, sp);
  }

  /// @brief Contructor for a polyline generated by a circle arc with "TRS" factors
  Polyline(float tc, size_t nc, R ep = 0, R tp = 0, R sp = 0, bool isOpen = false)
  {
    assert(tc >= limits::MinTc && tc <= limits::MaxTc 
      && nc >= limits::MinNc && nc <= limits::MaxNc);
    _np = tc < 360 ? nc + 1 : nc;
    set(tc, nc, ep, tp, sp, isOpen);
  }

  auto& length() const
  {
    return _np;
  }

  auto& points() const
  {
    return _points;
  }

  auto& bounds() const
  {
    return _bounds;
  }

  auto width() const
  {
    return static_cast<size_t>(abs(_bounds[0][0] - _bounds[1][0]));
  }

  auto height() const
  {
    return static_cast<size_t>(abs(_bounds[0][1] - _bounds[1][1]));
  }

  void set(const R& ep, const R& tp, const R& sp);

  void set(const R& tc, const size_t& nc, const R& ep, const R& tp, const R& sp, bool isOpen);

private:
  index_t _np{};
  vec3 _points[2 * limits::MaxNp];
  bounds _bounds{};

}; // Polyline

template<IsReal R> using poly = Polyline<R>;

