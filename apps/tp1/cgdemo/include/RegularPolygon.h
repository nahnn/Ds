#ifndef __RegularPolygon_h
#define __RegularPolygon_h

#include "Polyline.h"
#include "cg/include/geometry/Bounds3.h"
#include <cassert>

namespace cg
{ // begin namespace cg

template<IsReal R>
struct RegularPolygonLimits: public PolylineLimits
{
  // nothing
}; //RegularPolygonLimits

template<IsReal R>
class RegularPolygon: public Polyline<R>
{
public:
  using type = RegularPolygon<R>;
  using value_type = R;
  using quat = Quaternion<R>;
  using vec3 = Vector3<R>;
  using mat3 = Matrix3x3<R>;
  using bounds = Bounds3<R>;
  using limits = RegularPolygonLimits<R>;

  /// @brief Contructor for a polyline generated by a regular polygon with "TRS" factors
  RegularPolygon(index_t np, R ep = 0, R tp = 0, R sp = 0):
    _np{np},
    _ep{ep},
    _tp{tp},
    _sp{sp}
  {
    assert(_np >= limits::MinNp && _np <= limits::MaxNp);
  }

  void set() override;

}; // RegularPolygon

}




#endif // __RegularPolygon_h