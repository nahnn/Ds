#ifndef __Polyline_h
#define __Polyline_h

#include "math/Vector3.h"

namespace cg
{ // begin namespace cg
using index_t = unsigned;

/// @brief Generatrix: Stands for the types of polyline generatrixes.
enum Generatrix
{
  RegularPolygon,
  CircleArc
}; // end Generatrix

/// @brief PolylineLimits: Represents the limits of transformations of a polyline
struct PolylineLimits
{
  // --- Polyline Points ---
  static const size_t minNp; // min np
  static const size_t maxNp; // max np

  // --- Polyline Angle ---
  static const float minTc; // min thetac
  static const float maxTc; // max thetac

  // --- Scale Transform ---
  static const float minSp; // min sp
  static const float maxSp; // max sp

  // --- Rotation Transform ---
  static const float minTp; // min thetap
  static const float maxTp; // max thetap

  // --- Extrusion ---
  static const float minEp; // min ep
  static const float maxEp; // max ep

  // --- Spiral Swap Transform ---

  // --- Torsion Swap Transform ---

}; // end PolylineLimits

/// @brief
// Polyline: Class that represents the discretization of a given curve.
template<IsReal R>
class Polyline
{
public:
  using type = Polyline<R>;
  using value_type = R;
  using vec3 = Vector3<R>;

  /// @brief Default constructor
  constexpr Polyline() = default;

  /// @brief Contructor for a polyline generated by o regular polygon
  Polyline(Generatrix, size_t);

  /// @brief Contructor for a polyline generated by a circle arc 
  Polyline(Generatrix, float, size_t);

private:
  index_t _np{};
  vec3 _points[];

}; // end Polyline

} // end namespace cg

#endif // __Polyline_h
